export const DEFAULT_CATEGORY_IDS = WORD_CATEGORIES.map((c) => c.id);

export function pickRandomWord(
  categoryIds: string[],
  excludeWords: Set<string> = new Set(),
): { word: string; categoryName: string } {
  const activeCategories =
    categoryIds.length > 0
      ? WORD_CATEGORIES.filter((c) => categoryIds.includes(c.id))
      : WORD_CATEGORIES;

  const pool: Array<{ word: string; categoryName: string }> = [];
  for (const cat of activeCategories) {
    for (const word of cat.words) {
      if (!excludeWords.has(word.toLowerCase())) {
        pool.push({ word, categoryName: cat.name });
      }
    }
  }

  // Fallback to full pool if everything was used
  const source =
    pool.length > 0
      ? pool
      : WORD_CATEGORIES.flatMap((cat) =>
          cat.words.map((word) => ({ word, categoryName: cat.name })),
        );

  const chosen = source[Math.floor(Math.random() * source.length)];
  return chosen;
}
